        <section>
            <h2>کار با داده‌ها در پانداس</h2>
<p>
در این بخش با روش‌های مختلف کار با داده‌ها در پانداس آشنا می‌شوید. از انتخاب ستون‌ها و سطرها گرفته تا فیلتر کردن و اعمال توابع روی داده‌ها.
</p>

<h3>انتخاب ستون‌ها</h3>
<p>
برای انتخاب یک ستون خاص از دیتافریم، از نام ستون به همراه براکت استفاده می‌کنیم:
</p>

<div class="code-box">
    <span class="lang-label">python</span>
    <code>
import pandas as pd<br>
<br>
df = pd.DataFrame({<br>
    'نام': ['علی', 'مریم', 'رضا'],<br>
    'سن': [25, 30, 22],<br>
    'شهر': ['تهران', 'اصفهان', 'شیراز']<br>
})<br>
<br>
# انتخاب یک ستون<br>
print(df['نام'])<br>
<br>
# انتخاب چند ستون<br>
print(df[['نام', 'شهر']])
    </code>
</div>

<h3>انتخاب سطرها با loc و iloc</h3>
<p>
برای انتخاب سطرها بر اساس ایندکس یا موقعیت از loc و iloc استفاده می‌شود:
</p>

<div class="code-box">
    <span class="lang-label">python</span>
    <code>
# انتخاب سطر با ایندکس (loc)<br>
print(df.loc[0])<br>
<br>
# انتخاب سطر با موقعیت (iloc)<br>
print(df.iloc[1])<br>
<br>
# انتخاب بازه‌ای از سطرها<br>
print(df.loc[0:2])
    </code>
</div>

<h3>فیلتر کردن داده‌ها</h3>
<p>
می‌توانید داده‌ها را بر اساس شرط مشخصی فیلتر کنید. به عنوان مثال، افرادی که سن آنها بیشتر از ۲۳ است:
</p>

<div class="code-box">
    <span class="lang-label">python</span>
    <code>
# فیلتر بر اساس شرط<br>
filtered = df[df['سن'] > 23]<br>
print(filtered)<br>
<br>
# ترکیب چند شرط<br>
filtered2 = df[(df['سن'] > 23) & (df['شهر'] == 'تهران')]<br>
print(filtered2)
    </code>
</div>

<h3>افزودن ستون جدید</h3>
<p>
برای افزودن ستون جدید به دیتافریم، کافی است نام ستون جدید را تعریف و مقداردهی کنید:
</p>

<div class="code-box">
    <span class="lang-label">python</span>
    <code>
# افزودن ستون جدید<br>
df['وضعیت'] = ['مجرد', 'متاهل', 'مجرد']<br>
print(df)<br>
<br>
# ایجاد ستون بر اساس ستون‌های دیگر<br>
df['سن_به_سال'] = df['سن'] * 1<br>
print(df)
    </code>
</div>

<h3>حذف ستون یا سطر</h3>
<p>
برای حذف ستون یا سطر از دستور drop استفاده می‌کنیم:
</p>

<div class="code-box">
    <span class="lang-label">python</span>
    <code>
# حذف ستون<br>
df = df.drop('وضعیت', axis=1)<br>
print(df)<br>
<br>
# حذف سطر (بر اساس ایندکس)<br>
df = df.drop(1)<br>
print(df)
    </code>
</div>
