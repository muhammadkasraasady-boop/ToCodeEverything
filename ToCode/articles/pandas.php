        <section>
            <h2>آموزش پایه‌های پانداس</h2>
<p>
در این بخش با مفاهیم پایه و نحوه کار با پانداس آشنا می‌شوید. ابتدا باید کتابخانه پانداس را نصب و سپس در پروژه خود فراخوانی کنید.
</p>

<h3>نصب پانداس</h3>
<p>
برای نصب پانداس کافی است از دستور pip در ترمینال یا خط فرمان استفاده کنید:
</p>

<div class="code-box">
    <span class="lang-label">python</span>
    <code>
pip install pandas
    </code>
</div>

<h3>فراخوانی پانداس</h3>
<p>
پس از نصب، برای استفاده از پانداس در کد خود، آن را با نام اختصاری pd فراخوانی می‌کنیم:
</p>

<div class="code-box">
    <span class="lang-label">python</span>
    <code>
import pandas as pd
    </code>
</div>

<h3>ایجاد دیتافریم ساده</h3>
<p>
یکی از رایج‌ترین کارها در پانداس، ایجاد دیتافریم از دیکشنری یا لیست است. در مثال زیر یک دیتافریم ساخته می‌شود:
</p>

<div class="code-box">
    <span class="lang-label">python</span>
    <code>
import pandas as pd
<br>
data = { <br>
    'نام': ['علی', 'مریم', 'رضا'], <br>
    'سن': [25, 30, 22], <br>
    'شهر': ['تهران', 'اصفهان', 'شیراز'] <br>
} <br>

df = pd.DataFrame(data) <br>
print(df) <br>
    </code>
</div>

<h3>خواندن فایل CSV</h3>
<p>
پانداس امکان خواندن انواع فایل‌های داده را با یک خط کد فراهم می‌کند. برای خواندن فایل CSV از دستور زیر استفاده می‌شود:
</p>

<div class="code-box">
    <span class="lang-label">python</span>
    <code>
df = pd.read_csv('file.csv') <br>
print(df.head())
    </code>
</div>
