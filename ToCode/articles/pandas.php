            <h2>پانداس (Pandas) چیست؟</h2>
<p>
پانداس قدرتمندترین و پرکاربردترین کتابخانه متن‌باز در زبان پایتون برای تحلیل و دستکاری داده است. این کتابخانه با ارائه ساختارهای داده‌ای سریع و انعطاف‌پذیر، کار با داده‌های جدولی و زمانی را به ساده‌ترین شکل ممکن تبدیل کرده است. اگر با صفحات گسترده (مثل اکسل) یا پایگاه‌های داده کار کرده باشید، پانداس همان ابزارها را با سرعتی چندین برابر و در قالبی برنامه‌نویسی در اختیار شما قرار می‌دهد.
</p>

<h3>ساختارهای اصلی پانداس</h3>
<p>
پانداس بر پایه دو ساختار داده کلیدی ساخته شده است. سری (Series) که یک ستون واحد از داده‌ها را نمایش می‌دهد و دیتافریم (DataFrame) که یک جدول دوبعدی با سطرها و ستون‌های نام‌دار است و دقیقاً مانند یک صفحه اکسل عمل می‌کند.
</p>

<h3>کاربردهای پانداس</h3>
<p>
با پانداس می‌توانید فایل‌های CSV، Excel، JSON و SQL را با تنها یک خط کد بخوانید یا ذخیره کنید. همچنین داده‌های خام را پاکسازی کرده، مقادیر گم‌شده را مدیریت کنید و ستون‌های جدید بسازید. عملیات گروه‌بندی، ادغام و فیلتر کردن داده‌ها به ساده‌ترین شکل ممکن انجام می‌شود و داده‌های حجیم با میلیون‌ها رکورد را با سرعت بالا پردازش می‌کند.
</p>

<h3>مخاطبان پانداس</h3>
<p>
متخصصان علم داده، تحلیلگران مالی، محققین، مهندسان یادگیری ماشین و هر کسی که با داده‌های جدولی سر و کار دارد، پانداس را به عنوان اولین انتخاب خود می‌شناسند. این کتابخانه به دلیل سادگی و قدرت بالا، به استاندارد طلایی تحلیل داده در اکوسیستم پایتون تبدیل شده است.
</p>
